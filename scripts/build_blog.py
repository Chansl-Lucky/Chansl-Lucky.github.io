def blog_page(posts: list[dict], header: str, footer: str) -> str:
    schema = {"@context": "https://schema.org", "@type": "Blog", "name": "Shilian Chen — Blog",
              "url": absolute("/blog/"), "description": BLOG_DESCRIPTION, "inLanguage": "en",
              "author": {"@type": "Person", "name": AUTHOR, "url": absolute("/")}}
    head = page_head("Blog — Shilian Chen", BLOG_DESCRIPTION, "/blog/", schema)
    if posts:
        cards = []
        for post in posts:
            path = f'/blog/{post["slug"]}/'
            thumbnail = (f'<img class="post-image" src="{text(post["image"])}" alt="" loading="lazy">'
                         if post.get("image") else "")
            tags = ' · '.join(text(tag) for tag in post["tags"])
            cards.append(f'''<article class="blog-post">{thumbnail}<div class="post-card-copy">
      <div class="article-meta"><time datetime="{post['date']}">{human_date(post['date'])}</time><span>{post['read_time']} min read</span></div>
      <h2><a href="{path}">{text(post['title'])}</a></h2><p>{text(post['summary'])}</p>
      {f'<p class="post-tags">{tags}</p>' if tags else ''}</div></article>''')
        listing = '<div class="blog-list">' + '\n'.join(cards) + '</div>'
    else:
        listing = '''<section class="blog-empty" aria-labelledby="empty-title">
    <p class="empty-eyebrow">A SPACE FOR IDEAS</p><h2 id="empty-title">Writing is on the way.</h2>
    <p>Research notes and essays will appear here. In the meantime, explore our published work or follow updates on X.</p>
    <div class="empty-links"><a href="/#publications">Explore publications ↗</a><a href="https://x.com/Shilian_Chen">Follow on X ↗</a></div>
  </section>'''
    return f'''<!doctype html>
<html lang="en"><head>
  {head}
</head><body>
{GENERATED_MARKER}
<a class="skip-link" href="#main">Skip to content</a>
{header}
<main id="main" class="page-shell blog-page">
  <header class="blog-header"><p class="kicker">RESEARCH NOTES</p><h1>Blog</h1>
    <p class="blog-intro">{BLOG_DESCRIPTION}</p>
    <div class="blog-topics"><span>Self-improvement</span><span>Continual learning</span><span>Real-world agents</span><a href="/blog/feed.xml">RSS ↗</a></div>
  </header>
  {listing}
  {author_block()}
</main>
{footer}
</body></html>
'''


def article_page(post: dict, header: str, footer: str, template: Template) -> str:
    schema = {"@context": "https://schema.org", "@type": "BlogPosting", "headline": post["title"],
              "description": post["summary"], "url": post["url"], "mainEntityOfPage": post["url"],
              "datePublished": post["date"], "dateModified": post["date"], "inLanguage": "en",
              "author": {"@type": "Person", "name": AUTHOR, "url": absolute("/")},
              "image": absolute(post.get("image") or "/assets/shilian-chen.png"),
              "isPartOf": {"@type": "Blog", "name": "Shilian Chen — Blog", "url": absolute("/blog/")}}
    headings = post["parsed"].headings
    toc = ""
    if len(headings) >= 2:
        items = ''.join(f'<li><a href="#{text(quote(anchor, safe="-_.~"))}">{text(label)}</a></li>' for anchor, label in headings)
        toc = f'<nav class="article-toc" aria-label="Table of contents"><h2>On this page</h2><ol>{items}</ol></nav>'
    share = "https://twitter.com/intent/tweet?" + urlencode({"text": post["title"], "url": post["url"]})
    return template.substitute(
        generated_marker=GENERATED_MARKER, header=header, footer=footer,
        head=page_head(post["title"] + " — Shilian Chen", post["summary"], f'/blog/{post["slug"]}/',
                       schema, post.get("image"), post["date"]),
        title=text(post["title"]), summary=text(post["summary"]), date=post["date"],
        human_date=human_date(post["date"]), read_time=post["read_time"], toc=toc,
        body=post["parsed"].body, share_url=text(share), canonical=text(post["url"]),
        author_block=author_block(),
    )


def xml_document(root: ET.Element) -> str:
    ET.indent(root, space="  ")
    return '<?xml version="1.0" encoding="UTF-8"?>\n' + ET.tostring(root, encoding="unicode") + '\n'


def rss(posts: list[dict]) -> str:
    ET.register_namespace("atom", "http://www.w3.org/2005/Atom")
    root = ET.Element("rss", {"version": "2.0"})
    channel = ET.SubElement(root, "channel")
    for key, value in {"title": "Shilian Chen — Blog", "link": absolute("/blog/"),
                       "description": BLOG_DESCRIPTION, "language": "en"}.items():
        ET.SubElement(channel, key).text = value
    ET.SubElement(channel, "{http://www.w3.org/2005/Atom}link", {
        "href": absolute("/blog/feed.xml"), "rel": "self", "type": "application/rss+xml"})
    for post in posts:
        item = ET.SubElement(channel, "item")
        for key, value in {"title": post["title"], "link": post["url"], "description": post["summary"],
                           "pubDate": format_datetime(datetime.combine(date.fromisoformat(post["date"]),
                                                                      datetime.min.time(), timezone.utc), usegmt=True)}.items():
            ET.SubElement(item, key).text = value
        ET.SubElement(item, "guid", {"isPermaLink": "true"}).text = post["url"]
        for tag in post["tags"]:
            ET.SubElement(item, "category").text = tag
    return xml_document(root)


def sitemap(posts: list[dict], source: str) -> str:
    namespace = "http://www.sitemaps.org/schemas/sitemap/0.9"
    ET.register_namespace("", namespace)
    root = ET.Element(f"{{{namespace}}}urlset")
    modified = re.findall(r'"dateModified"\s*:\s*"(\d{4}-\d{2}-\d{2})"', source)
    site_date = max([SITE_DATE] + modified)
    blog_date = max([site_date] + [post["date"] for post in posts])
    entries = [(absolute("/"), site_date), (absolute("/blog/"), blog_date)]
    entries += [(post["url"], post["date"]) for post in posts]
    for location, changed in entries:
        node = ET.SubElement(root, f"{{{namespace}}}url")
        ET.SubElement(node, f"{{{namespace}}}loc").text = location
        ET.SubElement(node, f"{{{namespace}}}lastmod").text = changed
    return xml_document(root)


def build(output_dir: Path) -> int:
    source = (ROOT / "index.html").read_text(encoding="utf-8")
    header = SharedMarkup(shared_block(source, "HEADER"), active_blog=True).result()
    footer = SharedMarkup(shared_block(source, "FOOTER")).result()
    posts = load_posts()
    template = Template((ROOT / "templates/post.html").read_text(encoding="utf-8"))
    # Prepare everything before touching published output: invalid posts cannot partly overwrite a build.
    output = {"blog/index.html": blog_page(posts, header, footer), "blog/feed.xml": rss(posts),
              "sitemap.xml": sitemap(posts, source)}
    for post in posts:
        output[f'blog/{post["slug"]}/index.html'] = article_page(post, header, footer, template)
    output_dir = output_dir.resolve()
    for relative, content in output.items():
        destination = output_dir / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8")
    # Remove only our own obsolete generated article pages, never authored files or assets.
    for old_page in (output_dir / "blog").glob("*/index.html"):
        if old_page.relative_to(output_dir).as_posix() not in output and GENERATED_MARKER in old_page.read_text(encoding="utf-8"):
            old_page.unlink()
            if not any(old_page.parent.iterdir()):
                old_page.parent.rmdir()
    print(f"Built blog with {len(posts)} published post(s) in {output_dir}")
    return len(posts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=ROOT,
                        help="Write generated files elsewhere for isolated preview/testing")
    args = parser.parse_args()
    try:
        build(args.output_dir)
    except (BuildError, OSError, KeyError) as exc:
        print(f"Blog build failed: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
