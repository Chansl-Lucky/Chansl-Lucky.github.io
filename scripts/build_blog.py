class BuildError(ValueError):
    pass


def text(value: object) -> str:
    return escape(str(value), quote=True)


def json_script(value: dict) -> str:
    return json.dumps(value, ensure_ascii=False).replace("<", "\\u003c")


def absolute(path: str) -> str:
    return BASE_URL + path


def human_date(value: str) -> str:
    parsed = date.fromisoformat(value)
    return f"{parsed.strftime('%B')} {parsed.day}, {parsed.year}"


class SharedMarkup(HTMLParser):
    """Keep shared navigation rooted at the site and select the Blog link."""

    def __init__(self, markup: str, active_blog: bool = False):
        super().__init__(convert_charrefs=False)
        self.parts: list[str] = []
        self.active_blog = active_blog
        self.feed(markup)
        self.close()

    def start(self, tag, attrs, closed=False):
        attrs = list(attrs)
        revised = []
        href = dict(attrs).get("href", "")
        for key, value in attrs:
            if key in ("href", "src") and value:
                if value.startswith("#"):
                    value = "/" + value
                elif not urlsplit(value).scheme and not value.startswith("/"):
                    value = "/" + value.removeprefix("./")
            if tag == "a" and self.active_blog:
                if key == "aria-current":
                    continue
                if key == "class" and value:
                    value = " ".join(x for x in value.split() if x != "active")
                    if not value:
                        continue
            revised.append((key, value))
        if tag == "a" and self.active_blog and href in ("/blog/", "blog/", "./blog/"):
            classes = next((value for key, value in revised if key == "class"), "")
            revised = [(key, value) for key, value in revised if key != "class"]
            revised.extend([("class", (classes + " active").strip()), ("aria-current", "page")])
        rendered = "".join(f" {key}" if value is None else f' {key}="{text(value)}"' for key, value in revised)
        self.parts.append(f"<{tag}{rendered}{' /' if closed else ''}>")

    def handle_starttag(self, tag, attrs):
        self.start(tag, attrs)

    def handle_startendtag(self, tag, attrs):
        self.start(tag, attrs, True)

    def handle_endtag(self, tag):
        self.parts.append(f"</{tag}>")

    def handle_data(self, data):
        self.parts.append(data)

    def handle_entityref(self, name):
        self.parts.append(f"&{name};")

    def handle_charref(self, name):
        self.parts.append(f"&#{name};")

    def handle_comment(self, data):
        self.parts.append(f"<!--{data}-->")

    def result(self):
        return "".join(self.parts)


class ArticleMarkup(HTMLParser):
    """Preserve trusted body HTML, adding stable IDs to second-level headings."""

    def __init__(self, markup: str):
        super().__init__(convert_charrefs=False)
        self.parts: list[str] = []
        self.headings: list[tuple[str, str]] = []
        self.ids: set[str] = set()
        self.words: list[str] = []
        self.heading: dict | None = None
        self.feed(markup)
        self.close()
        if self.heading:
            raise BuildError("An article contains an unclosed h2 heading")

    def handle_starttag(self, tag, attrs):
        attributes = dict(attrs)
        node_id = attributes.get("id")
        if node_id:
            if node_id in self.ids:
                raise BuildError(f"Duplicate HTML id in article: {node_id}")
            self.ids.add(node_id)
        if tag == "h2":
            if self.heading:
                raise BuildError("An article contains nested h2 headings")
            self.heading = {"index": len(self.parts), "attrs": attrs, "text": []}
        self.parts.append(self.get_starttag_text())

    def handle_startendtag(self, tag, attrs):
        self.parts.append(self.get_starttag_text())

    def handle_endtag(self, tag):
        if tag == "h2" and self.heading:
            heading = self.heading
            label = " ".join("".join(heading["text"]).split())
            attrs = heading["attrs"]
            node_id = dict(attrs).get("id")
            if not node_id:
                stem = re.sub(r"[^a-z0-9]+", "-", label.lower()).strip("-") or "section"
                node_id = stem
                suffix = 2
                while node_id in self.ids:
                    node_id = f"{stem}-{suffix}"
                    suffix += 1
                self.ids.add(node_id)
                raw = self.parts[heading["index"]]
                self.parts[heading["index"]] = raw[:-1] + f' id="{text(node_id)}">'
            self.headings.append((node_id, label or "Section"))
            self.heading = None
        self.parts.append(f"</{tag}>")

    def handle_data(self, data):
        self.parts.append(data)
        self.words.extend(re.findall(r"\b\w+\b", data))
        if self.heading:
            self.heading["text"].append(data)

    def handle_entityref(self, name):
        self.parts.append(f"&{name};")
        if self.heading:
            from html import unescape
            self.heading["text"].append(unescape(f"&{name};"))

    def handle_charref(self, name):
        self.parts.append(f"&#{name};")
        if self.heading:
            from html import unescape
            self.heading["text"].append(unescape(f"&#{name};"))

    def handle_comment(self, data):
        self.parts.append(f"<!--{data}-->")

    @property
    def body(self):
        return "".join(self.parts)


def shared_block(source: str, name: str) -> str:
    start, end = f"<!-- SITE_{name}_START -->", f"<!-- SITE_{name}_END -->"
    if source.count(start) != 1 or source.count(end) != 1:
        raise BuildError(f"index.html needs exactly one {start} and {end}")
    return source.split(start, 1)[1].split(end, 1)[0].strip()


def local_file(value: str, field: str) -> Path:
    candidate = Path(value)
    if candidate.is_absolute() or ".." in candidate.parts:
        raise BuildError(f"{field} must be a safe path relative to the repository root")
    resolved = (ROOT / candidate).resolve()
    if not resolved.is_relative_to(ROOT) or not resolved.is_file():
        raise BuildError(f"Missing or unsafe {field} file: {value}")
    return resolved


def load_posts() -> list[dict]:
    try:
        entries = json.loads((ROOT / "content/posts.json").read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise BuildError(f"Cannot read content/posts.json: {exc}") from exc
    if not isinstance(entries, list):
        raise BuildError("content/posts.json must contain a JSON array")
    posts, slugs = [], set()
    for index, entry in enumerate(entries):
        if not isinstance(entry, dict):
            raise BuildError(f"Post {index + 1} must be an object")
        if "published" in entry and not isinstance(entry["published"], bool):
            raise BuildError(f"Post {index + 1}: published must be true or false")
        if entry.get("published") is not True:
            continue
        for field in ("slug", "title", "date", "summary", "body"):
            if not isinstance(entry.get(field), str) or not entry[field].strip():
                raise BuildError(f"Post {index + 1}: {field} must be a non-empty string")
        slug = entry["slug"]
        if not re.fullmatch(r"[a-z0-9]+(?:-[a-z0-9]+)*", slug):
            raise BuildError(f"Unsafe slug: {slug!r}; use lowercase letters, digits, and hyphens")
        if slug in slugs:
            raise BuildError(f"Duplicate slug: {slug}")
        slugs.add(slug)
        try:
            if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", entry["date"]):
                raise ValueError()
            date.fromisoformat(entry["date"])
        except ValueError as exc:
            raise BuildError(f"Invalid date for {slug}: expected a real YYYY-MM-DD date") from exc
        body_path = local_file(entry["body"], "body")
        if body_path.suffix.lower() != ".html":
            raise BuildError(f"Body for {slug} must be an HTML fragment file")
        tags = entry.get("tags", [])
        if not isinstance(tags, list) or not all(isinstance(tag, str) and tag.strip() for tag in tags):
            raise BuildError(f"Tags for {slug} must be a list of non-empty strings")
        post_image = entry.get("image")
        if post_image is not None:
            if not isinstance(post_image, str) or not post_image.startswith("/assets/"):
                raise BuildError(f"Image for {slug} must be a root-relative /assets/ path")
            local_file(post_image.lstrip("/"), "image")
        parsed = ArticleMarkup(body_path.read_text(encoding="utf-8"))
        posts.append({**entry, "tags": tags, "parsed": parsed, "url": absolute(f"/blog/{slug}/"),
                      "read_time": max(1, math.ceil(len(parsed.words) / 220))})
    return sorted(posts, key=lambda item: (item["date"], item["slug"]), reverse=True)


